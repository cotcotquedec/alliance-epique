"""Generate addon/ForeverSpeech/data/game_voices.lua: the file IDs of the game's own NPC voice lines, muted in game
while the option is on (2026-10-10: the greetings and farewells get in the way now that quests are read).

Input: the Wowhead Classic "NPC Greetings" sound list in the local cache (data/cache/wowhead/classic_sounds_type_17.html,
fetched 2026-10-05; Wowhead is not crawled any more): 275 sound kits (greetings, farewells, "pissed" lines, vendor
greetings, unique lore voices), about 1 470 files. Their IDs are FileDataIDs, the same in every locale. Personal use:
the generated file is not committed (docs/reference/npc-voices.md).

    python -m pipeline.game_voices [--page data/cache/wowhead/classic_sounds_type_17.html] [--out ...]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

VERSION = 1
REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PAGE = REPO_ROOT / "data" / "cache" / "wowhead" / "classic_sounds_type_17.html"
DEFAULT_OUT = REPO_ROOT / "addon" / "ForeverSpeech" / "data" / "game_voices.lua"
HEADER = "-- GENERATED by pipeline/game_voices.py: do not edit by hand.\n"
PER_LINE = 10

_DECODER = json.JSONDecoder()


def sound_kits(page: str) -> list[dict]:
    """Rows of the page's sound Listview (`new Listview({"id":"sounds", ... "data":[...]})`, strict JSON)."""
    start = page.find("new Listview(")
    data_at = page.find('"data":', start) if start >= 0 else -1
    if data_at < 0:
        raise ValueError("no sound Listview in the page")
    rows, _ = _DECODER.raw_decode(page, page.find("[", data_at))
    return rows


def file_ids(kits: list[dict]) -> list[int]:
    """Every file of every kit, sorted, each once."""
    return sorted({int(f["id"]) for kit in kits for f in kit.get("files", [])})


def render(ids: list[int], kits: int) -> str:
    lines = [HEADER,
             f"-- The game's NPC voice lines ({kits} sound kits, {len(ids)} files), muted while the option is on.\n",
             "ForeverSpeechGameVoices = {\n", f"  version = {VERSION},\n", "  files = {\n"]
    for i in range(0, len(ids), PER_LINE):
        lines.append("    " + " ".join(f"{n}," for n in ids[i:i + PER_LINE]) + "\n")
    lines += ["  },\n", "}\n"]
    return "".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--page", type=Path, default=DEFAULT_PAGE)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    kits = sound_kits(args.page.read_text(encoding="utf-8"))
    ids = file_ids(kits)
    args.out.write_text(render(ids, len(kits)), encoding="utf-8")
    print(f"wrote {args.out}: {len(kits)} sound kits, {len(ids)} files")


if __name__ == "__main__":
    main()
