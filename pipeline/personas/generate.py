"""Persona sheets of the quest givers, one per NPC, in data/voices.json.

A persona is generated by Claude (pipeline/llm.py) from a dossier built only from our registries:
the NPC, its game voice and the texts of the quests it gives and ends. The prompt is a versioned
file (prompt_v<N>.md), the model is pinned, and the answer must match PERSONA_SCHEMA.

Reproducibility: each persona stores the hash of its inputs (dossier, prompt, schema, model). A
rerun only regenerates NPCs whose inputs changed (new quests, new prompt version), or with --force.
The results are committed, so the voices built on them do not change by accident.
"""

from __future__ import annotations

import hashlib
import json
import threading
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

from pipeline import storage
from pipeline.llm import LLMError, LLMLimit, claude_json

PROMPT_VERSION = 5  # v3 (2026-10-06): race, for NPCs without a game voice; v4 (2026-10-10): dialogues;
# v5 (2026-10-11): the NPC's verified sex (registry `sex`, from the Wowhead NPC pages until 2026-10-12) is a fact, kept as is
PROMPT_FILE = Path(__file__).with_name(f"prompt_v{PROMPT_VERSION}.md")
MODEL = "claude-sonnet-5-5"
EFFORT = "medium"
SCHEMA_VERSION = 1


def voices_file() -> Path:
    return storage.DATA_DIR / "voices.json"


PERSONA_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["summary", "sex", "sex_evidence", "race", "age", "temperament", "register", "pace", "energy",
                 "speech_traits", "default_emotion", "voice_description_en", "voice_description_fr",
                 "sample_line", "confidence"],
    "properties": {
        "summary": {"type": "string", "description": "Qui est ce PNJ, en 1 à 3 phrases."},
        "sex": {"type": "string", "enum": ["male", "female"]},
        "sex_evidence": {"type": "string", "enum": ["game_voice", "model", "title_or_text", "name_only"]},
        "race": {"type": "string", "enum": ["Human", "Dwarf", "Gnome", "NightElf", "Orc", "Troll", "Tauren",
                                            "Undead", "Goblin", "Other"]},
        "age": {"type": "string", "enum": ["enfant", "adolescent", "jeune adulte", "adulte", "mûr", "âgé"]},
        "temperament": {"type": "array", "items": {"type": "string"}, "minItems": 2, "maxItems": 5},
        "register": {"type": "string", "enum": ["familier", "courant", "soutenu", "militaire", "rustique", "savant"]},
        "pace": {"type": "string", "enum": ["lent", "posé", "normal", "vif"]},
        "energy": {"type": "string", "enum": ["basse", "moyenne", "haute"]},
        "speech_traits": {"type": "string", "description": "Manière de parler, tics, diction."},
        "default_emotion": {"type": "string"},
        "voice_description_en": {"type": "string"},
        "voice_description_fr": {"type": "string"},
        "sample_line": {"type": "string"},
        "confidence": {"type": "string", "enum": ["haute", "moyenne", "basse"]},
    },
}


def validate(persona: dict) -> list[str]:
    """Problems with a persona (empty list when valid). Claude Code enforces the schema; this
    double-checks it, plus the length rules of the prompt."""
    problems = []
    props = PERSONA_SCHEMA["properties"]
    for key in PERSONA_SCHEMA["required"]:
        if key not in persona:
            problems.append(f"missing {key}")
    for key, value in persona.items():
        spec = props.get(key)
        if spec is None:
            problems.append(f"unknown field {key}")
        elif "enum" in spec and value not in spec["enum"]:
            problems.append(f"{key}={value!r} not in {spec['enum']}")
        elif spec["type"] == "string" and (not isinstance(value, str) or not value.strip()):
            problems.append(f"{key} must be a non-empty string")
        elif spec["type"] == "array" and not (isinstance(value, list) and spec["minItems"] <= len(value) <= spec["maxItems"]):
            problems.append(f"{key} must be a list of {spec['minItems']} to {spec['maxItems']} items")
    if isinstance(persona.get("voice_description_en"), str) and not 20 <= len(persona["voice_description_en"]) <= 1000:
        problems.append("voice_description_en must be 20 to 1000 characters (Voice Design limit)")
    if isinstance(persona.get("sample_line"), str) and not 100 <= len(persona["sample_line"]) <= 1000:
        problems.append("sample_line must be 100 to 1000 characters (Voice Design preview text)")
    return problems


def zone_registries(zone_dirs: list[Path]) -> tuple[dict[int, dict], dict[int, dict], dict[int, list[str]]]:
    """NPCs and quests over the given zones, and the zones each NPC appears in."""
    npcs: dict[int, dict] = {}
    quests: dict[int, dict] = {}
    npc_zones: dict[int, list[str]] = {}
    for folder in zone_dirs:
        npc_file = storage.read_json(folder / "npcs.json") or {}
        quest_file = storage.read_json(folder / "quests.json") or {}
        for key, npc in npc_file.get("npcs", {}).items():
            npcs[int(key)] = npc
            npc_zones.setdefault(int(key), []).append(npc_file.get("zone_name") or npc_file.get("zone"))
        for key, quest in quest_file.get("quests", {}).items():
            quests[int(key)] = quest
    return npcs, quests, npc_zones


def dossier(npc: dict, quests: dict[int, dict], zones: list[str], dialogues: list[str] | None = None) -> dict:
    """Everything the persona is based on, in a stable order. `dialogues`: the texts of its dialogue window
    (pipeline/foreverdb/dialogues.py), only for an NPC who has some (the dossier of the others is unchanged)."""
    voice = npc.get("voice") or {}
    given = [q for q in quests.values() if any(s.get("type") == "npc" and s.get("id") == npc["id"]
                                                for s in q.get("starters", []))]
    ended = [q for q in quests.values() if any(e.get("type") == "npc" and e.get("id") == npc["id"]
                                                for e in q.get("enders", []))]
    return {
        "npc": {
            "id": npc["id"], "name": npc.get("name"), "title": npc.get("title"), "type": npc.get("type"),
            "react": npc.get("react"), "faction": npc.get("faction"), "levels": npc.get("levels"),
            "zones": sorted(set(z for z in zones if z)),
            "new_in_forever": (npc.get("forever") or {}).get("status") == "new",
        },
        "game_voice": {k: voice.get(k) for k in ("kind", "set", "race", "sex", "personality", "reason")
                       if voice.get(k) is not None},
        **({"sex": {"value": npc["sex"]["value"], "source": "game_voice" if npc["sex"]["source"] == "game_voice"
                    else "model"}} if (npc.get("sex") or {}).get("value") else {}),
        "quests_given": [{"id": q["id"], "name": q.get("name"), "description": q.get("description"),
                          "objectives": q.get("objectives")} for q in sorted(given, key=lambda q: q["id"])],
        "quests_ended": [{"id": q["id"], "name": q.get("name"), "completion": q.get("completion")}
                         for q in sorted(ended, key=lambda q: q["id"]) if q.get("completion")],
        **({"dialogues": list(dialogues)} if dialogues else {}),
    }


def prompt_text() -> str:
    return PROMPT_FILE.read_text(encoding="utf-8")


def input_hash(file: dict) -> str:
    payload = json.dumps({"dossier": file, "prompt": prompt_text(), "schema": PERSONA_SCHEMA,
                          "model": MODEL, "effort": EFFORT}, ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def user_message(file: dict) -> str:
    return "Dossier du PNJ :\n```json\n" + json.dumps(file, ensure_ascii=False, indent=1) + "\n```"


def load_voices() -> dict:
    return storage.read_json(voices_file()) or {"schema": SCHEMA_VERSION, "npcs": {}}


def dialogue_texts(zone_dirs: list[Path]) -> dict[int, list[str]]:
    """NPC -> the texts of its dialogue pages (dialogues.json of the given zones), at most 6, first page first."""
    out: dict[int, list[str]] = {}
    for folder in zone_dirs:
        for key, npc in ((storage.read_json(folder / "dialogues.json") or {}).get("npcs") or {}).items():
            out.setdefault(int(key), []).extend(p["text"] for p in npc.get("pages", []))
    return {k: v[:6] for k, v in out.items()}


def todo(npcs: dict[int, dict], quests: dict[int, dict], npc_zones: dict[int, list[str]],
         voices: dict, force: bool = False, only: set[int] | None = None,
         dialogues: dict[int, list[str]] | None = None) -> list[tuple[int, dict, str]]:
    """(npc id, dossier, hash) for each NPC without a persona. A persona already generated is kept even
    if its dossier changed since (new quests, another zone): regenerating it would redo its scripts
    and audio. force=True regenerates them all."""
    out = []
    for nid in sorted(npcs):
        if only and nid not in only:
            continue
        if not force and voices["npcs"].get(str(nid)):
            continue
        file = dossier(npcs[nid], quests, npc_zones.get(nid, []), (dialogues or {}).get(nid))
        out.append((nid, file, input_hash(file)))
    return out


def generate(jobs: list[tuple[int, dict, str]], voices: dict, workers: int = 4, bare: bool = False,
             call=claude_json, log=print) -> dict:
    """Generates the personas, saving data/voices.json after each one (an interruption loses nothing)."""
    lock = threading.Lock()
    system = prompt_text()
    report = {"generated": 0, "failed": [], "cost_usd": 0.0, "stopped": None}
    limit = threading.Event()  # usage limit reached: the jobs not started yet are left for the next run

    def one(nid: int, file: dict, digest: str):
        if limit.is_set():
            raise LLMLimit("skipped")
        answer = call(system, user_message(file), PERSONA_SCHEMA, MODEL, EFFORT, bare=bare)
        known = file.get("sex")
        if known and answer.data.get("sex") != known["value"]:  # a verified sex is a fact (v5): never overridden
            answer.data.update(sex=known["value"], sex_evidence=known["source"])
        problems = validate(answer.data)
        if problems:
            raise LLMError("; ".join(problems))
        return nid, file, digest, answer

    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {pool.submit(one, *job): job[0] for job in jobs}
        for future in as_completed(futures):
            nid = futures[future]
            try:
                _, file, digest, answer = future.result()
            except LLMLimit as err:
                limit.set()
                report["stopped"] = report["stopped"] or str(err)
                continue
            except (LLMError, OSError) as err:
                report["failed"].append(nid)
                log(f"  {nid}: FAILED {err}")
                continue
            with lock:
                previous = voices["npcs"].get(str(nid)) or {}
                voices["npcs"][str(nid)] = {
                    "npc_id": nid,
                    "name": file["npc"]["name"],
                    "title": file["npc"]["title"],
                    "zones": file["npc"]["zones"],
                    "game_voice": file["game_voice"],
                    "persona": answer.data,
                    "generator": {"prompt_version": PROMPT_VERSION, "model": answer.model, "effort": EFFORT,
                                  "input_hash": digest, "generated_at": storage.now(),
                                  "cost_usd": round(answer.cost_usd, 4)},
                    # the voice loop's text and Qwen3 voice (tools/voices), kept across regenerations
                    **{k: previous[k] for k in ("voice_text", "qwen", "qwen_history") if k in previous},
                }
                voices["npcs"] = storage.by_id(voices["npcs"])
                voices["schema"] = SCHEMA_VERSION
                storage.write_json(voices_file(), voices)
                report["generated"] += 1
                report["cost_usd"] += answer.cost_usd
            p = answer.data
            log(f"  {nid} {file['npc']['name']}: {p['sex']}, {p['age']}, {', '.join(p['temperament'])}")
    return report
