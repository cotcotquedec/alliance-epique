"""Generate addon/ForeverSpeech/data/index.lua (index contract v9, CLAUDE.md section 8).

Inputs:
- the zone registries data/zones/**/{quests,npcs}.json: quest -> giver and ender NPCs, NPC -> display ID
  and name, so that the player window can show any speaker's 3D model (SetDisplayInfo, S8);
- the produced quest audio data/zones/**/audio.json: kind "detail" (acceptance) and "complete" (turn-in);
- an optional JSON file mapping questID -> {kind -> audio entry} with the contract fields
  (npc, voice, file, fileF, dur, src).
A text no NPC says is read by the narrator, Elise (pipeline/narrator.py, v4): her audio entries name her, the quest
keeps no giver or ender, and npcs gets her name without a display ID (the player shows the quest icon).
v5 (2026-10-11): Elise's zone introductions (pipeline/zone_intros/), keyed by the client's map ID: the zone's area
ID, French and English names, her text (the client's speech synthesis reads it while no audio exists) and the
audio entry once made (data/zones/<group>/@intros/{scripts,audio}.json). v6 (2026-10-11): her level-up lines, by
level, the same way (data/zones/@elise/levels/). v7 (2026-10-14): the level of each quest (the registries'), for the
player window's level badge when the quest is not in the quest log. v8 (2026-10-15): the companion journal's
friendship tiers and Elise's lines for each tier (D18, data/zones/@elise/companions/), by line ID (tier place x 100
+ variant). v9 (2026-10-21): the books read by Elise (D19, data/zones/@books/), by the key of their French title
(pipeline/match.py fs_key), page by page, each page a list of {fp, intro} (fp: fs_fp of the page's text, to tell two
books of the same title apart); and the NPCs' dialogue pages that have an audio (D14, D15: a refused take still
plays), by NPC: {page, words, intro} (words: the fs_norm tokens of the base text, for the addon's matching in game).

    python -m pipeline.build_index [--entries data/index_entries.json] [--zones data/zones] [--out ...]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from pipeline import books as book_pages, companion_lines, narrator
from pipeline.match import from_markup, fs_key, words

INDEX_VERSION = 9  # v3 (2026-10-06): kind "complete" and the ender of each quest; v4 (2026-10-10): the narrator;
# v5 (2026-10-11): zones, Elise's zone introductions; v6 (2026-10-11): levels, her level-up lines;
# v7 (2026-10-14): the level of each quest; v8 (2026-10-15): companions, the friendship tiers and Elise's lines;
# v9 (2026-10-21): books (D19) and dialogues (D14)
COMPANION_TIER_FIELDS = ("key", "name", "nameF", "from", "rank")
FIELD_ORDER = ("npc", "voice", "file", "fileF", "dur", "src")
NPC_FIELD_ORDER = ("display", "name")
KINDS = ("detail", "complete")  # acceptance (D6) and turn-in texts; never the progress text
AUDIO_SECTION = {"detail": "audio", "complete": "complete"}  # section of audio.json for each kind
SOURCES = {"capture", "wowhead_fr", "wowhead_en_tr", "test", "elise"}
ZONE_FIELD_ORDER = ("area", "name", "nameEn", "text")
INTRO_FIELD_ORDER = ("npc", "voice", "file", "dur", "src")
VOICED_FIELD_ORDER = ("npc", "voice", "file", "fileF", "dur", "src")  # books and dialogues (v9)

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = REPO_ROOT / "addon" / "ForeverSpeech" / "data" / "index.lua"
DEFAULT_ZONES = REPO_ROOT / "data" / "zones"

HEADER = "-- GENERATED by pipeline/build_index.py: do not edit by hand.\n"


def lua_string(value: str) -> str:
    out = ['"']
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 32:
            out.append(f"\\{ord(ch):03d}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(round(value, 2))
    if isinstance(value, str):
        return lua_string(value)
    raise TypeError(f"unsupported value for the index: {value!r}")


def validate_entry(quest_id: int, kind: str, entry: dict) -> None:
    if kind not in KINDS:
        raise ValueError(f"quest {quest_id}: unknown kind {kind!r}")
    unknown = set(entry) - set(FIELD_ORDER)
    if unknown:
        raise ValueError(f"quest {quest_id}/{kind}: unknown fields {sorted(unknown)}")
    if not entry.get("file"):
        raise ValueError(f"quest {quest_id}/{kind}: 'file' is required")
    if entry.get("src") not in SOURCES:
        raise ValueError(f"quest {quest_id}/{kind}: src must be one of {sorted(SOURCES)}")


def _fields(lines: list[str], indent: str, entry: dict, order: tuple[str, ...]) -> None:
    for field in order:
        value = entry.get(field)
        if value is not None:  # nil fields are simply omitted
            lines.append(f"{indent}{field} = {lua_value(value)},")


def render_index(quests: dict[int, dict[str, dict]], givers: dict[int, int] | None = None,
                 npcs: dict[int, dict] | None = None, enders: dict[int, int] | None = None,
                 zones: dict[int, dict] | None = None, levels: dict[int, dict] | None = None,
                 quest_levels: dict[int, int] | None = None, companions: dict | None = None,
                 books: dict | None = None, dialogues: dict | None = None) -> str:
    """quests: questID -> {kind -> audio entry}; givers / enders: questID -> giver / ender NPC id;
    npcs: NPC id -> {display, name}; zones: map ID -> {area, name, nameEn, text, intro: audio entry or None};
    quest_levels: questID -> quest level (v7); companions: load_companions (v8); books: load_books, dialogues:
    load_dialogues (v9)."""
    givers = givers or {}
    enders = enders or {}
    npcs = npcs or {}
    quest_levels = quest_levels or {}
    lines = [HEADER, "ForeverSpeechIndex = {", f"  version = {INDEX_VERSION},", "  quests = {"]
    for quest_id in sorted(set(quests) | set(givers) | set(enders) | set(quest_levels)):
        lines.append(f"    [{int(quest_id)}] = {{")
        if quest_id in quest_levels:
            lines.append(f"      level = {int(quest_levels[quest_id])},")
        if quest_id in givers:
            lines.append(f"      giver = {int(givers[quest_id])},")
        if quest_id in enders:
            lines.append(f"      ender = {int(enders[quest_id])},")
        for kind in sorted(quests.get(quest_id, {})):
            entry = quests[quest_id][kind]
            validate_entry(quest_id, kind, entry)
            lines.append(f"      {kind} = {{")
            _fields(lines, "        ", entry, FIELD_ORDER)
            lines.append("      },")
        lines.append("    },")
    lines += ["  },", "  npcs = {"]
    for npc_id in sorted(npcs):
        lines.append(f"    [{int(npc_id)}] = {{")
        _fields(lines, "      ", npcs[npc_id], NPC_FIELD_ORDER)
        lines.append("    },")
    lines += ["  },", "  zones = {"]
    for map_id in sorted(zones or {}):
        zone = zones[map_id]
        lines.append(f"    [{int(map_id)}] = {{")
        _fields(lines, "      ", zone, ZONE_FIELD_ORDER)
        if zone.get("intro"):
            lines.append("      intro = {")
            _fields(lines, "        ", zone["intro"], INTRO_FIELD_ORDER)
            lines.append("      },")
        lines.append("    },")
    lines += ["  },", "  levels = {"]
    for level in sorted(levels or {}):
        entry = levels[level]
        lines.append(f"    [{int(level)}] = {{")
        _fields(lines, "      ", entry, ("text",))
        if entry.get("intro"):
            lines.append("      intro = {")
            _fields(lines, "        ", entry["intro"], INTRO_FIELD_ORDER)
            lines.append("      },")
        lines.append("    },")
    lines += ["  },", "  companions = {", "    tiers = {"]
    for tier in (companions or {}).get("tiers", []):
        fields = ", ".join(f"{k} = {lua_value(tier[k])}" for k in COMPANION_TIER_FIELDS if tier.get(k) is not None)
        lines.append(f"      {{ {fields} }},")
    lines += ["    },", "    lines = {"]
    for line_id in sorted((companions or {}).get("lines", {})):
        entry = companions["lines"][line_id]
        lines.append(f"      [{int(line_id)}] = {{")
        _fields(lines, "        ", entry, ("tier", "text"))
        if entry.get("intro"):
            lines.append("        intro = {")
            _fields(lines, "          ", entry["intro"], INTRO_FIELD_ORDER)
            lines.append("        },")
        lines.append("      },")
    lines += ["    },", "  },", "  books = {"]
    for key in sorted(books or {}):
        book = books[key]
        lines += [f"    [{lua_string(key)}] = {{", f"      title = {lua_string(book['title'])},", "      pages = {"]
        for n in sorted(book["pages"]):
            lines.append(f"        [{int(n)}] = {{")
            for entry in book["pages"][n]:
                lines.append(f"          {{ fp = {lua_string(entry['fp'])}" + (
                    f", intro = {_inline(entry['intro'])} }}," if entry.get("intro") else " },"))
            lines.append("        },")
        lines += ["      },", "    },"]
    lines += ["  },", "  dialogues = {"]
    for npc in sorted(dialogues or {}):
        lines.append(f"    [{int(npc)}] = {{")
        for page in dialogues[npc]:
            lines.append(f"      {{ page = {lua_string(page['page'])}, words = {lua_string(page['words'])}, "
                         f"intro = {_inline(page['intro'])} }},")
        lines.append("    },")
    lines += ["  },", "}", ""]
    return "\n".join(lines)


def _inline(entry: dict) -> str:
    """An audio entry on one line: { npc = 1000000, voice = "...", file = "...", dur = 31.2, src = "elise" }."""
    return "{ " + ", ".join(f"{k} = {lua_value(entry[k])}" for k in VOICED_FIELD_ORDER
                            if entry.get(k) is not None) + " }"


def load_registries(zones_dir: Path) -> tuple[dict[int, int], dict[int, dict], dict[int, int]]:
    """Quest -> first NPC giver, quest -> first NPC ender, and the display ID and name of those NPCs,
    over all zones."""
    givers: dict[int, int] = {}
    enders: dict[int, int] = {}
    npcs: dict[int, dict] = {}
    for path in sorted(zones_dir.glob("**/quests.json")):
        for key, quest in json.loads(path.read_text(encoding="utf-8"))["quests"].items():
            for field, out in (("starters", givers), ("enders", enders)):
                npc = next((s["id"] for s in quest.get(field, []) if s["type"] == "npc"), None)
                if npc is not None:
                    out[int(key)] = npc
    speakers = set(givers.values()) | set(enders.values())
    for path in sorted(zones_dir.glob("**/npcs.json")):
        for key, npc in json.loads(path.read_text(encoding="utf-8"))["npcs"].items():
            if int(key) in speakers and (npc.get("display_id") or npc.get("name")):
                npcs[int(key)] = {"display": npc.get("display_id"), "name": npc.get("name")}
    return givers, npcs, enders


def load_quest_levels(zones_dir: Path) -> dict[int, int]:
    """Quest -> its level in the registries (v7), over all zones; a level of 0 or less (unknown) is left out."""
    levels: dict[int, int] = {}
    for path in sorted(zones_dir.glob("**/quests.json")):
        for key, quest in json.loads(path.read_text(encoding="utf-8"))["quests"].items():
            level = quest.get("level")
            if isinstance(level, int) and level > 0:
                levels[int(key)] = level
    return levels


def load_audio(zones_dir: Path, voices: dict | None = None) -> dict[int, dict[str, dict]]:
    """Entries of every kind from the produced quest audio (data/zones/**/audio.json)."""
    out: dict[int, dict[str, dict]] = {}
    for path in sorted(zones_dir.glob("**/audio.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for kind in KINDS:
            for key, item in (data.get(AUDIO_SECTION[kind]) or {}).items():
                if "m" not in item:
                    continue
                npc = item["npc"]
                # the voice of the take, not the NPC's current one (a restored voice gets a new id)
                voice_id = item["m"].get("stamp", {}).get("voice") or \
                    (((voices or {}).get(str(npc)) or {}).get("voice") or {}).get("voice_id") or "v1"
                out.setdefault(int(key), {})[kind] = {
                    "npc": npc,
                    "voice": f"npc{npc}@{voice_id[:8]}",
                    "file": item["m"]["file"],
                    "fileF": (item.get("f") or {}).get("file"),
                    "dur": item["m"]["dur"],
                    "src": "wowhead_fr",
                }
    return out


def _intro(item: dict | None) -> dict | None:
    if not item:
        return None
    voice = (item.get("stamp") or {}).get("voice") or item.get("voice_id") or "v1"
    return {"npc": narrator.NARRATOR_ID, "voice": f"npc{narrator.NARRATOR_ID}@{voice[:8]}", "file": item["file"],
            "dur": item["dur"], "src": "elise"}


def load_zones(zones_dir: Path) -> dict[int, dict]:
    """Elise's zone introductions (data/zones/<group>/@intros/): map ID -> {area, name, nameEn, text, intro}."""
    out: dict[int, dict] = {}
    for path in sorted(zones_dir.glob("*/@intros/scripts.json")):
        scripts = json.loads(path.read_text(encoding="utf-8")).get("zones") or {}
        audio_file = path.with_name("audio.json")
        audio = (json.loads(audio_file.read_text(encoding="utf-8")).get("zone") or {}) if audio_file.exists() else {}
        for area, script in scripts.items():
            if not script.get("text") or not script.get("map"):
                continue
            intro = _intro((audio.get(str(area)) or {}).get("m"))
            out[int(script["map"])] = {"area": int(area), "name": script.get("name"), "nameEn": script.get("name_en"),
                                       "text": script["text"], "intro": intro}
    return out


def load_levels(zones_dir: Path) -> dict[int, dict]:
    """Elise's level-up lines (data/zones/@elise/levels/): level -> {text, intro}."""
    folder = zones_dir / "@elise" / "levels"
    if not (folder / "scripts.json").exists():
        return {}
    scripts = json.loads((folder / "scripts.json").read_text(encoding="utf-8")).get("levels") or {}
    audio = (json.loads((folder / "audio.json").read_text(encoding="utf-8")).get("level") or {}) \
        if (folder / "audio.json").exists() else {}
    return {int(level): {"text": s["text"], "intro": _intro((audio.get(str(level)) or {}).get("m"))}
            for level, s in scripts.items() if s.get("text")}


def load_companions(zones_dir: Path) -> dict:
    """Elise's companion lines (D18, data/zones/@elise/companions/, pipeline/companion_lines/): {"tiers": [...],
    "lines": {ID: {tier, text, intro}}}, the tiers in order; empty without the scripts. Audio: audio.json, section
    "companion", by line ID (tier place x 100 + variant, as the Elise loop writes it)."""
    folder = zones_dir / companion_lines.KEY
    if not (folder / "scripts.json").exists():
        return {}
    scripts = json.loads((folder / "scripts.json").read_text(encoding="utf-8"))
    audio = (json.loads((folder / "audio.json").read_text(encoding="utf-8")).get("companion") or {}) \
        if (folder / "audio.json").exists() else {}
    tiers = [{"key": t["key"], "name": t["name_m"], "nameF": t["name_f"], "from": int(t["from_seconds"]),
              "rank": t.get("rank")} for t in scripts["tiers"]]
    lines = {line["id"]: {"tier": line["tier"], "text": line["text"],
                          "intro": _intro((audio.get(str(line["id"])) or {}).get("m"))}
             for line in companion_lines.lines(scripts)}
    return {"tiers": tiers, "lines": lines}


def _voiced(item: dict | None, npc: int, src: str, female: dict | None = None) -> dict | None:
    """An index audio entry (v9) from an audio.json variant entry (and the female one, if any)."""
    if not item:
        return None
    voice = (item.get("stamp") or {}).get("voice") or item.get("voice_id") or "v1"
    return {"npc": npc, "voice": f"npc{npc}@{voice[:8]}", "file": item["file"],
            "fileF": (female or {}).get("file"), "dur": item["dur"], "src": src}


def load_books(zones_dir: Path) -> dict[str, dict]:
    """The books read by Elise (D19, data/zones/@books/): fs_key(title) -> {title, pages: {n: [{fp, intro}]}}. Only
    the books of the scripts (Alliance scope, French title) and their French pages; a page without audio keeps its
    fp alone, so that the addon knows the book. Two books with the same title and page give one entry."""
    folder = book_pages.folder(zones_dir)
    registry = _read_json(folder / book_pages.REGISTRY)
    scripts = (_read_json(folder / "scripts.json") or {}).get(book_pages.SECTION) or {}
    audio = (_read_json(folder / "audio.json") or {}).get(book_pages.AUDIO_SECTION) or {}
    out: dict[str, dict] = {}
    for _, book in sorted(((registry or {}).get("books") or {}).items()):
        if not book.get("title") or not any(str(p["page"]) in scripts for p in book["pages"]):
            continue
        entry = out.setdefault(book["key"], {"title": book["title"], "pages": {}})
        for page in book["pages"]:
            if str(page["page"]) not in scripts:
                continue
            item = audio.get(str(page["page"])) or {}
            record = {"fp": page["fp"], "intro": _voiced(item.get("m"), narrator.NARRATOR_ID, "elise", item.get("f"))}
            listed = entry["pages"].setdefault(page["n"], [])
            if record not in listed:
                listed.append(record)
    return out


def load_dialogues(zones_dir: Path, voices: dict | None = None) -> dict[int, list[dict]]:
    """The NPCs' dialogue pages with an audio (D14; D15: a refused take is in place too): NPC -> [{page, words,
    intro}], in the order of dialogues.json (first page first). words: the base text's tokens (pipeline/match.py),
    from the page's female text when the NPC is a woman and the base has one (as the scripts do)."""
    out: dict[int, list[dict]] = {}
    for path in sorted(zones_dir.glob("**/dialogue_audio.json")):
        audio = (_read_json(path) or {}).get("dialogues") or {}
        npcs = (_read_json(path.with_name("dialogues.json")) or {}).get("npcs") or {}
        for nid, npc in sorted(npcs.items(), key=lambda kv: int(kv[0])):
            female = ((((voices or {}).get(nid) or {}).get("persona") or {}).get("sex")) == "female"
            for page in npc.get("pages", []):
                item = audio.get(f"{nid}_{page['id']}") or {}
                intro = _voiced(item.get("m"), int(nid), "qwen", item.get("f"))
                if not intro:
                    continue
                text = page.get("text_female") if female and page.get("text_female") else page["text"]
                out.setdefault(int(nid), []).append({"page": str(page["id"]), "words": words(from_markup(text)),
                                                     "intro": intro})
    return out


def _read_json(path: Path) -> dict | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def load_entries(path: Path | None) -> dict[int, dict[str, dict]]:
    if path is None:
        return {}
    raw = json.loads(path.read_text(encoding="utf-8"))
    return {int(qid): kinds for qid, kinds in raw.items()}


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--entries", type=Path)
    parser.add_argument("--zones", type=Path, default=DEFAULT_ZONES)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    givers, npcs, enders = load_registries(args.zones)
    voices_file = args.zones.parent / "voices.json"
    voices = json.loads(voices_file.read_text(encoding="utf-8"))["npcs"] if voices_file.exists() else {}
    entries = {**load_audio(args.zones, voices), **load_entries(args.entries)}
    zones, levels = load_zones(args.zones), load_levels(args.zones)
    quest_levels, companions = load_quest_levels(args.zones), load_companions(args.zones)
    books, dialogues = load_books(args.zones), load_dialogues(args.zones, voices)
    if zones or levels or companions or books \
            or any(narrator.is_narrator(e.get("npc")) for kinds in entries.values() for e in kinds.values()):
        npcs[narrator.NARRATOR_ID] = {"name": (voices.get(str(narrator.NARRATOR_ID)) or {}).get("name", narrator.NAME)}
    args.out.write_text(render_index(entries, givers, npcs, enders, zones, levels, quest_levels, companions, books,
                                     dialogues), encoding="utf-8")
    kinds = {k: sum(1 for e in entries.values() if k in e) for k in KINDS}
    print(f"wrote {args.out}: {len(givers)} quest givers, {len(enders)} enders, {len(npcs)} NPCs, "
          f"{len(quest_levels)} quest levels, "
          f"audio {kinds}, zones {len(zones)} ({sum(1 for z in zones.values() if z['intro'])} with audio), "
          f"levels {len(levels)} ({sum(1 for v in levels.values() if v['intro'])} with audio), "
          f"companion lines {len(companions.get('lines', {}))} "
          f"({sum(1 for v in companions.get('lines', {}).values() if v['intro'])} with audio), "
          f"books {len(books)} ({sum(1 for b in books.values() for p in b['pages'].values() for e in p if e['intro'])} "
          f"pages with audio), dialogues {sum(len(v) for v in dialogues.values())} pages of {len(dialogues)} NPCs; "
          f"{args.out.stat().st_size} bytes")


if __name__ == "__main__":
    main()
