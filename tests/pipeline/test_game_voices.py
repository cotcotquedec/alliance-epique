from pipeline.game_voices import file_ids, main, render, sound_kits

PAGE = """<script>new Listview({"id":"sounds","template":"sound","data":[
{"id":5974,"name":"HumanMaleStandardNPCGreetings","type":17,"files":[{"id":543353,"title":"a"},{"id":543355,"title":"b"}]},
{"id":5975,"name":"HumanMaleStandardVendorNPCGreetings","type":17,"files":[{"id":543355,"title":"b"},{"id":540001}]},
{"id":5976,"name":"Chicken","type":17}
]});</script>"""


def test_every_file_once_sorted():
    kits = sound_kits(PAGE)
    assert len(kits) == 3
    assert file_ids(kits) == [540001, 543353, 543355]


def test_render_is_a_lua_table():
    out = render([540001, 543353], 2)
    assert out.startswith("-- GENERATED by pipeline/game_voices.py")
    assert "ForeverSpeechGameVoices = {\n  version = 1,\n  files = {\n    540001, 543353,\n  },\n}\n" in out


def test_main_writes_the_addon_file(tmp_path):
    page, out = tmp_path / "page.html", tmp_path / "game_voices.lua"
    page.write_text(PAGE, encoding="utf-8")
    main(["--page", str(page), "--out", str(out)])
    assert "540001, 543353, 543355," in out.read_text(encoding="utf-8")
