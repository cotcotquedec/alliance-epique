"""Actor of the dialogues loop: one round over one or more categories, in the oracle's order (runs in .venv-voices,
called by tools/dialogues/actor.sh), like the readings actor (tools/readings/act.py).

1. Candidates left by an interrupted pass are judged first (dropped if their reading is settled meanwhile).
2. Each dialogue reading still to do (oracle.zone_dialogues; FS_NPCS="823 197": only these NPCs) gets ONE candidate
   take with a seed it never had, generated by tools/dialogues/generate.py while the judge hears each one as soon
   as it is written. Inside a loop, the models are the run's model servers, loaded once.

    .venv-voices/bin/python -m tools.dialogues.act eastern-kingdoms/elwynn-forest [...]
"""

from __future__ import annotations

import json
import random
import subprocess
import sys
import time

from tools.dialogues import judge, oracle
from tools.loop import progress
from tools.qwen_voices import server


def new_seed(used: set[int], rng=random.SystemRandom()) -> int:
    while True:
        seed = rng.randrange(1, 2 ** 31)
        if seed not in used:
            return seed


def drop_orphans(zone: str) -> None:
    for take in (judge.CANDIDATES / judge.flat(zone)).glob("*.wav"):
        if not take.with_suffix(".json").exists():
            take.unlink()


def voices() -> dict:
    return json.loads(judge.voice_judge.VOICES_FILE.read_text(encoding="utf-8"))["npcs"]


def main(argv: list[str] | None = None) -> int:
    zones = sys.argv[1:] if argv is None else argv
    if not zones:
        print("usage: python -m tools.dialogues.act <zone key>...", file=sys.stderr)
        return 2
    board = progress.actor("dialogues", zones)
    remote = server.connect("dialogues", "ears", say=lambda line: print(line, flush=True))
    ears = server.RemoteEars(remote) if remote else None

    def hearing():
        nonlocal ears
        ears = ears or judge.Ears()
        return ears

    board.update(phase="judging takes left by an interrupted pass")
    for zone in zones:
        drop_orphans(zone)
        left = judge.candidates(zone)
        if left:
            todo = {u["id"] for u in oracle.zone_dialogues(zone, voices())["todo"]}
            print(f"{zone}: {len(left)} candidate(s) from an interrupted pass, judged first", flush=True)
            for take in left:
                if json.loads(take.with_suffix(".json").read_text(encoding="utf-8"))["id"] not in todo:
                    take.with_suffix(".json").unlink()
                    take.unlink()
                    continue
                judge.judge_take(zone, take, hearing())
    wanted, records, jobs = oracle.only_npcs(), voices(), []
    for zone in zones:
        todo = oracle.zone_dialogues(zone, records)["todo"]
        print(f"{zone}: {len(todo)} dialogue reading(s) to do" + (f" (NPCs {sorted(wanted)})" if wanted else ""),
              flush=True)
        state = judge._read(judge.state_file(zone), {"readings": {}})["readings"]
        for u in todo:
            voice = records[str(u["npc"])]["qwen"]
            jobs.append({**u, "zone": zone, "seed": new_seed(set((state.get(u["id"]) or {}).get("seeds", []))),
                         "voice_seed": voice["seed"], "voice_ref": voice["ref"]})
    counts = {"ok": 0, "pending": 0, "not_found": 0}
    board.update(takes=len(jobs))
    if jobs:
        print(f"round: {len(jobs)} dialogue reading(s) in {len(zones)} categor{'y' if len(zones) == 1 else 'ies'}",
              flush=True)
        generator = subprocess.Popen([sys.executable, "-m", "tools.dialogues.generate"], stdin=subprocess.PIPE,
                                     text=True, cwd=judge.ROOT)
        generator.stdin.write(json.dumps(jobs, ensure_ascii=False))
        generator.stdin.close()
        expected = {f"{j['id']}_s{j['seed']}": j["zone"] for j in jobs}
        board.update(phase="generating and judging")
        while expected:
            ready = [(z, t) for z in sorted(set(expected.values())) for t in judge.candidates(z) if t.stem in expected]
            for zone, take in ready:
                verdict = judge.judge_take(zone, take, hearing())
                counts[verdict] += 1
                del expected[take.stem]
                board.update(judged=board.data["judged"] + 1,
                             **{{"pending": "failed"}.get(verdict, verdict): counts[verdict]})
            if not ready:
                if generator.poll() is not None:
                    break
                time.sleep(1)
        code = generator.wait()
        for zone in zones:
            drop_orphans(zone)
        if code:
            print(f"round: the generator exited with {code}", flush=True)
            return code
    from pipeline import review
    review.publish_refused("dialogue", zones)  # a refused page is played in game until a take passes
    print(f"round: {counts['ok']} new dialogue reading(s), {counts['pending']} failed, {counts['not_found']} not "
          "found in this run", flush=True)
    board.update(phase="done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
