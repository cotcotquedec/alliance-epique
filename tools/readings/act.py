"""Actor of the readings loop: one round over one or more categories, in the oracle's order (runs in .venv-voices,
called by tools/readings/actor.sh; the loop chooses the categories of a round, tools/loop/engine.py).

1. In each category, candidates left by an interrupted pass are judged first (dropped if their reading is already in
   place), then the kept best takes that pass the current thresholds are promoted (judge.rejudge_kept).
2. Each reading of these categories still to do (oracle.zone_readings, optionally only some NPCs:
   FS_NPCS="823 197") gets ONE candidate take, with a random seed it never had. The takes are generated by a
   separate process (tools/readings/generate.py) while the judge (tools/readings/judge.py, Whisper and ECAPA) hears
   each one as soon as it is written: both run side by side. Inside a loop, the models are the run's model server
   (tools/qwen_voices/server.py), loaded once for the whole run.
3. The addon's index is rebuilt (pipeline/build_index.py): an accepted reading plays in game after /reload.
4. Each category's listening page is rewritten (tools/readings/page.py).

    .venv-voices/bin/python -m tools.readings.act eastern-kingdoms/elwynn-forest [kalimdor/teldrassil ...]
"""

from __future__ import annotations

import json
import random
import subprocess
import sys
import time

from tools.loop import progress
from tools.qwen_voices import server
from tools.readings import judge, oracle, page


def new_seed(used: set[int], rng=random.SystemRandom()) -> int:
    while True:
        seed = rng.randrange(1, 2 ** 31)
        if seed not in used:
            return seed


def drop_orphans(zone: str) -> None:
    """Deletes candidate takes without their meta: a generation interrupted before the end, never judged."""
    for take in (judge.CANDIDATES / judge.flat(zone)).glob("*.wav"):
        if not take.with_suffix(".json").exists():
            take.unlink()


def voices() -> dict:
    return json.loads(judge.voice_judge.VOICES_FILE.read_text(encoding="utf-8"))["npcs"]


def main(argv: list[str] | None = None) -> int:
    zones = sys.argv[1:] if argv is None else argv
    if not zones:
        print("usage: python -m tools.readings.act <zone key>...", file=sys.stderr)
        return 2
    board = progress.actor("readings", zones)
    remote = server.connect("readings", "ears", say=lambda line: print(line, flush=True))
    ears = server.RemoteEars(remote) if remote else None

    def hearing():
        nonlocal ears
        ears = ears or judge.Ears()
        return ears

    board.update(phase="judging takes left by an interrupted pass")
    for zone in zones:
        drop_orphans(zone)
        left = judge.candidates(zone)
        if left:
            done = {u["id"] for u in oracle.zone_readings(zone, voices())["todo"]}
            print(f"{zone}: {len(left)} candidate(s) from an interrupted pass, judged first", flush=True)
            for take in left:
                if json.loads(take.with_suffix(".json").read_text(encoding="utf-8"))["id"] not in done:
                    take.with_suffix(".json").unlink()  # its reading is settled meanwhile: never redone
                    take.unlink()
                    continue
                judge.judge_take(zone, take, hearing())
        promoted = judge.rejudge_kept(zone)
        if promoted:
            print(f"{zone}: {promoted} kept take(s) pass the current thresholds", flush=True)
    wanted, records, jobs = oracle.only_npcs(), voices(), []
    for zone in zones:
        todo = oracle.zone_readings(zone, records)["todo"]
        print(f"{zone}: {len(todo)} reading(s) to do" + (f" (NPCs {sorted(wanted)})" if wanted else ""), flush=True)
        state = (json.loads(judge.state_file(zone).read_text(encoding="utf-8")) if judge.state_file(zone).exists()
                 else {"readings": {}})["readings"]
        for u in todo:
            voice = records[str(u["npc"])]["qwen"]  # the oracle keeps only readings whose NPC has its voice
            jobs.append({**u, "zone": zone, "seed": new_seed(set((state.get(u["id"]) or {}).get("seeds", []))),
                         "voice_seed": voice["seed"], "voice_ref": voice["ref"]})
    counts = {"ok": 0, "pending": 0, "not_found": 0}
    board.update(takes=len(jobs))
    if jobs:
        print(f"round: {len(jobs)} reading(s) in {len(zones)} categor{'y' if len(zones) == 1 else 'ies'}", flush=True)
        generator = subprocess.Popen([sys.executable, "-m", "tools.readings.generate"], stdin=subprocess.PIPE,
                                     text=True, cwd=judge.ROOT)
        generator.stdin.write(json.dumps(jobs, ensure_ascii=False))
        generator.stdin.close()
        expected = {f"{j['id']}_s{j['seed']}": j["zone"] for j in jobs}
        board.update(phase="generating and judging")
        while expected:
            ready = [(z, t) for z in sorted(set(expected.values())) for t in judge.candidates(z) if t.stem in expected]
            for zone, take in ready:
                verdict = judge.judge_take(zone, take, hearing())
                counts[verdict] += 1
                del expected[take.stem]
                board.update(judged=board.data["judged"] + 1,
                             **{{"pending": "failed"}.get(verdict, verdict): counts[verdict]})
            if not ready:
                if generator.poll() is not None:
                    break
                time.sleep(1)
        code = generator.wait()
        for zone in zones:
            drop_orphans(zone)
        if code:
            print(f"round: the generator exited with {code}", flush=True)
            return code
    board.update(phase="building the addon index")
    from pipeline import build_index, review
    review.publish_refused("reading", zones)  # a refused reading is played in game until a take passes
    build_index.main([])
    records = voices()
    for zone in zones:
        left = oracle.zone_readings(zone, records)
        print(f"{zone}: {len(left['todo'])} reading(s) left, {left['ok']} in place; page: {page.write(zone)}",
              flush=True)
    print(f"round: {counts['ok']} new reading(s), {counts['pending']} failed, {counts['not_found']} not found "
          f"in this run", flush=True)
    board.update(phase="done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
